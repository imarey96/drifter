package render

import (
	"fmt"
	"io"
	"strings"

	"github.com/imarey96/drifter/pkg/engine"
)

// MarkdownMarker is an HTML comment embedded in every report so CI bots can
// find and update their previous PR comment instead of posting a new one.
const MarkdownMarker = "<!-- drifter-report -->"

type MarkdownOptions struct {
	Title       string
	ShowIgnored bool
	// MaxAttributes caps attribute lines per resource in the diff blocks.
	MaxAttributes int
}

// Markdown writes a GitHub/GitLab-flavoured summary suitable for a PR comment.
func Markdown(w io.Writer, r *engine.Report, opt MarkdownOptions) error {
	if opt.Title == "" {
		opt.Title = "Infrastructure drift report"
	}
	if opt.MaxAttributes == 0 {
		opt.MaxAttributes = 25
	}
	var b strings.Builder
	b.WriteString(MarkdownMarker + "\n")
	fmt.Fprintf(&b, "## %s\n\n", opt.Title)

	s := r.Summary
	status := "**No drift detected.**"
	if s.Errors == s.Workspaces {
		status = ""
	}
	if s.Drifted > 0 {
		status = fmt.Sprintf("**%d resource%s drifted** across %d workspace%s.", s.Drifted, plural(s.Drifted), s.Workspaces, plural(s.Workspaces))
	}
	if s.Errors > 0 {
		status += fmt.Sprintf(" **%d workspace%s failed to scan.**", s.Errors, plural(s.Errors))
	}
	fmt.Fprintf(&b, "%s\n\n", status)

	b.WriteString("| Workspace | Out-of-band | Unapplied | Added | Modified | Destroyed | Replaced | Ignored |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|---:|---:|\n")
	for _, ws := range r.Workspaces {
		if ws.Error != nil {
			fmt.Fprintf(&b, "| `%s` | scan failed | – | – | – | – | – | – |\n", ws.Path)
			continue
		}
		c := countWorkspace(ws)
		fmt.Fprintf(&b, "| `%s` | %d | %d | %d | %d | %d | %d | %d |\n",
			ws.Path, c.OutOfBand, c.Unapplied, c.Added, c.Modified, c.Destroyed, c.Replaced, c.Ignored)
	}
	b.WriteString("\n")

	for _, ws := range r.Workspaces {
		if ws.Error != nil {
			fmt.Fprintf(&b, "<details><summary><code>%s</code>: scan failed</summary>\n\n", ws.Path)
			fmt.Fprintf(&b, "**%s**\n\n", mdEscape(ws.Error.Message))
			if ws.Error.Detail != "" {
				fmt.Fprintf(&b, "```\n%s\n```\n\n", ws.Error.Detail)
			}
			if ws.Error.Hint != "" {
				fmt.Fprintf(&b, "Hint: %s\n\n", mdEscape(ws.Error.Hint))
			}
			b.WriteString("</details>\n\n")
			continue
		}
		var shown []engine.ResourceDrift
		for _, rd := range ws.Resources {
			if !rd.Ignored || opt.ShowIgnored {
				shown = append(shown, rd)
			}
		}
		if len(shown) == 0 {
			continue
		}
		fmt.Fprintf(&b, "<details><summary><code>%s</code>: %d resource%s</summary>\n\n", ws.Path, len(shown), plural(len(shown)))
		b.WriteString("| | Resource | Action | Origin | Attributes |\n|---|---|---|---|---|\n")
		for _, rd := range shown {
			origin := originLabel(rd.Origin)
			if rd.Ignored {
				origin = "ignored"
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s |\n",
				actionSymbol(rd.Action), rd.Address, rd.Action, origin, mdEscape(changedPaths(rd, 5)))
		}
		b.WriteString("\n")
		for _, rd := range shown {
			writeDiffBlock(&b, rd, opt.MaxAttributes)
		}
		b.WriteString("</details>\n\n")
	}

	fmt.Fprintf(&b, "<sub>Generated by drifter at %s</sub>\n", r.GeneratedAt.Format("2006-01-02 15:04 MST"))
	_, err := io.WriteString(w, b.String())
	return err
}

func writeDiffBlock(b *strings.Builder, rd engine.ResourceDrift, maxAttrs int) {
	if rd.Action != engine.ActionModified || (len(rd.OutOfBand) == 0 && len(rd.Planned) == 0) {
		return
	}
	fmt.Fprintf(b, "**`%s`**\n\n```diff\n", rd.Address)
	section := func(title string, cs []engine.AttributeChange) {
		if len(cs) == 0 {
			return
		}
		fmt.Fprintf(b, "# %s\n", title)
		n := 0
		for _, c := range cs {
			if c.Ignored {
				continue
			}
			if n == maxAttrs {
				fmt.Fprintf(b, "# … %d more\n", len(cs)-n)
				break
			}
			n++
			switch c.Kind {
			case engine.ChangeAdded:
				fmt.Fprintf(b, "+ %s = %s\n", c.Path, formatValue(c.After, c.Unknown, 200))
			case engine.ChangeRemoved:
				fmt.Fprintf(b, "- %s = %s\n", c.Path, formatValue(c.Before, false, 200))
			default:
				fmt.Fprintf(b, "- %s = %s\n+ %s = %s\n", c.Path, formatValue(c.Before, false, 200), c.Path, formatValue(c.After, c.Unknown, 200))
			}
		}
	}
	section("changed outside IaC (last applied → live)", rd.OutOfBand)
	section("live vs code (live → config)", rd.Planned)
	b.WriteString("```\n\n")
}

func countWorkspace(ws engine.WorkspaceReport) engine.Summary {
	r := engine.Report{Workspaces: []engine.WorkspaceReport{ws}}
	r.Summarize()
	return r.Summary
}

func mdEscape(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ", "<", "&lt;", ">", "&gt;").Replace(s)
}
